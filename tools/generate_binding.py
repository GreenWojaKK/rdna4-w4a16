"""Generate ctypes declarations from the public C header. --check detects stale bindings."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    header = re.sub(r"//[^\n]*", "", (ROOT / "kernels/api.h").read_text(encoding="utf-8"))
    version = re.search(r"#define RDNA4_W4A16_ABI_VERSION (\d+)", header)[1]
    lines = ['"""Generated by tools/generate_binding.py from kernels/api.h; do not edit."""',
             "import ctypes as c", "from enum import IntEnum", "", f"ABI_VERSION = {version}", ""]
    for name, body in re.findall(r"enum rdna4_w4a16_(\w+)\s*{([^}]+)}", header):
        lines += ["", f"class {name.title()}(IntEnum):"]
        for constant, value in re.findall(r"RDNA4_W4A16_\w+?_" + r"(\w+)\s*=\s*(-?\d+)", body):
            lines.append(f"    {constant} = {value}")
    types = {"uint32_t": "c.c_uint32", "int32_t": "c.c_int32", "int64_t": "c.c_int64",
             "const char*": "c.c_char_p", "const char**": "c.POINTER(c.c_char_p)",
             "const uint32_t*": "c.c_void_p", "const uint16_t*": "c.c_void_p", "uint16_t*": "c.c_void_p"}
    lines += ["", "", "SIGNATURES = {"]
    functions = re.findall(r"RDNA4_W4A16_API\s+([^;{}\n]+?)\s+(w4a16_\w+)\(([^)]*)\);", header)
    if len(functions) != len(re.findall(r"^RDNA4_W4A16_API\s", header, re.MULTILINE)):
        raise ValueError("unsupported public declaration; update the binding generator")
    for result, name, params in functions:
        args = [] if params == "void" else [types[p.strip().rsplit(" ", 1)[0]] for p in params.split(",")]
        lines.append(f'    "{name}": ({types[result]}, [{", ".join(args)}]),')
    lines += ["}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    target = ROOT / "_rdna4_w4a16_abi.py"
    source = generate()
    if "--check" in sys.argv:
        if not target.is_file() or target.read_text(encoding="utf-8") != source:
            raise SystemExit("stale ctypes declarations; run tools/generate_binding.py")
    else:
        target.write_text(source, encoding="utf-8", newline="\n")
